from pathlib import Path
import json
import hashlib
import numpy as np
import pandas as pd
import sklearn
import joblib

from sklearn.ensemble import RandomForestClassifier

ROOT = Path(__file__).resolve().parents[1]
DATA_PATH = ROOT / "data" / "vibration_features.csv"
MODEL_DIR = ROOT / "models"
MODEL_PATH = MODEL_DIR / "vibration_classifier.joblib"
METADATA_PATH = MODEL_DIR / "vibration_metadata.json"

LABELS = ["Faulty", "Healthy"]
EXCLUDED = {
    "recording_id", "label", "n_rows",
    "rpm", "humidity", "temperature",
}

def main():
    if not DATA_PATH.exists():
        raise FileNotFoundError(f"Missing feature table: {DATA_PATH}")
    if MODEL_PATH.exists() or METADATA_PATH.exists():
        raise FileExistsError(
            "Vibration artifact already exists. Refusing to overwrite it."
        )

    df = pd.read_csv(DATA_PATH)
    required = {"recording_id", "label"} | EXCLUDED
    missing = required - set(df.columns)
    if missing:
        raise ValueError(f"Missing required columns: {sorted(missing)}")

    feature_columns = [
        c for c in df.select_dtypes(include="number").columns
        if c not in EXCLUDED
    ]
    if len(feature_columns) != 27:
        raise ValueError(
            f"Expected 27 numeric signal features, got {len(feature_columns)}"
        )
    if df["recording_id"].duplicated().any():
        raise ValueError("Duplicate recording IDs detected.")
    if set(df["label"].unique()) != set(LABELS):
        raise ValueError(f"Unexpected labels: {df['label'].unique().tolist()}")

    X = df[feature_columns].to_numpy(dtype=float)
    y = df["label"].to_numpy()
    if not np.isfinite(X).all():
        raise ValueError("Non-finite feature values detected.")

    model = RandomForestClassifier(
        n_estimators=300,
        class_weight="balanced",
        random_state=42,
        n_jobs=-1,
    )
    model.fit(X, y)

    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    joblib.dump(model, MODEL_PATH, compress=3)

    source_hash = hashlib.sha256(DATA_PATH.read_bytes()).hexdigest()
    metadata = {
        "model_name": "EngineGuard vibration baseline",
        "task": "binary bearing-condition classification",
        "labels": LABELS,
        "feature_columns": feature_columns,
        "feature_count": len(feature_columns),
        "training_recordings": int(len(df)),
        "class_counts": {
            str(k): int(v) for k, v in df["label"].value_counts().items()
        },
        "algorithm": "RandomForestClassifier",
        "parameters": {
            "n_estimators": 300,
            "class_weight": "balanced",
            "random_state": 42,
        },
        "training_data": "data/vibration_features.csv",
        "training_data_sha256": source_hash,
        "scikit_learn_version": sklearn.__version__,
        "joblib_version": joblib.__version__,
        "historical_evaluation": {
            "random_recording_holdout": {
                "accuracy": 0.9412,
                "balanced_accuracy": 0.9328,
                "macro_f1": 0.9328,
                "test_recordings": 34,
                "note": "Historical report; not a fresh evaluation of this fitted artifact."
            },
            "condition_grouped_cross_validation": {
                "accuracy": 0.9104,
                "balanced_accuracy": 0.9043,
                "macro_f1": 0.8996,
                "folds": 5,
                "note": "Historical report; groups were operating conditions, not physical engines."
            }
        },
        "limitations": [
            "Small dataset: 134 recordings.",
            "No independent physical-engine or laboratory validation.",
            "Frequency features are normalized bins, not calibrated Hz.",
            "Predictions are experimental decision support, not safety certification.",
            "Historical metrics have not been independently regenerated by this script."
        ]
    }
    METADATA_PATH.write_text(json.dumps(metadata, indent=2), encoding="utf-8")

    print("Vibration model trained and saved.")
    print("Model:", MODEL_PATH)
    print("Metadata:", METADATA_PATH)
    print("Training recordings:", len(df))
    print("Features:", len(feature_columns))
    print("Classes:", model.classes_.tolist())
    print("Model bytes:", MODEL_PATH.stat().st_size)

if __name__ == "__main__":
    main()
